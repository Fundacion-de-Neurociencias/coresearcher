"""
python/discovery/lean_formalization_engine.py - Lean 4 Interactive Theorem Prover Gate & Formalization Engine (ADR-DISCOVERY-047).

Synthesizes, audits, and verifies Lean 4 formal mathematical code from scientific claims,
equations, and proof DAGs. Bridges unverified LaTeX prose with deterministic kernel truth.
"""

from __future__ import annotations

import enum
import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


class LeanProofStatus(enum.Enum):
    """Formal verification status of a Lean 4 manuscript or theorem."""
    FULLY_VERIFIED_KERNEL = "FULLY_VERIFIED_KERNEL"      # Compiled without error, zero 'sorry'
    CONTAINS_UNPROVEN_SORRY = "CONTAINS_UNPROVEN_SORRY"  # Syntactically valid but relies on unproven 'sorry'
    SYNTAX_OR_TYPE_ERROR = "SYNTAX_OR_TYPE_ERROR"        # Fails Lean parsing or type-checking
    UNVERIFIED_PROSE_ONLY = "UNVERIFIED_PROSE_ONLY"      # No Lean code provided
    NOT_KERNEL_CHECKED = "NOT_KERNEL_CHECKED"            # Lean binary unavailable: only static checks ran


@dataclass
class LeanVerificationReport:
    """Detailed audit report of a Lean 4 formalization."""
    theorem_name: str
    status: LeanProofStatus
    is_kernel_sound: bool
    contains_sorry: bool
    sorry_count: int
    used_axioms: List[str] = field(default_factory=list)
    tactics_used: List[str] = field(default_factory=list)
    compiler_diagnostics: str = ""
    lean_source_code: str = ""
    som_lean_formalization_hash: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "theorem_name": self.theorem_name,
            "status": self.status.value,
            "is_kernel_sound": self.is_kernel_sound,
            "contains_sorry": self.contains_sorry,
            "sorry_count": self.sorry_count,
            "used_axioms": self.used_axioms,
            "tactics_used": self.tactics_used,
            "compiler_diagnostics": self.compiler_diagnostics,
            "lean_source_code": self.lean_source_code,
            "som_lean_formalization_hash": self.som_lean_formalization_hash,
        }


class LeanFormalizationEngine:
    """
    Autonomous Lean 4 Code Generator and Verifier.
    Enforces ADR-DISCOVERY-047.
    """

    @classmethod
    def synthesize_lean4_scaffolding(
        cls,
        theorem_name: str,
        hypothesis_statement: str,
        premises: Optional[List[str]] = None,
        symbolic_identity: Optional[str] = None,
        auto_tactics: Optional[List[str]] = None,
    ) -> str:
        """
        Synthesizes modular Lean 4 source code from a scientific statement.
        """
        clean_name = re.sub(r"[^a-zA-Z0-9_]", "_", theorem_name).strip("_")
        premises_list = premises or []
        tactics = auto_tactics or ["intro h", "ring"]

        lines = [
            f"-- Generated by CoResearcher Lean 4 Formalization Engine (ADR-DISCOVERY-047)",
            f"-- Theorem: {theorem_name}",
            f"-- Mathematical claim: {hypothesis_statement}",
            "import Mathlib",
            "",
            "namespace CoResearcher.Discovery",
            "",
        ]

        # Add premise definitions if any
        for idx, prem in enumerate(premises_list, 1):
            lines.append(f"-- Premise {idx}: {prem}")

        # Synthesize theorem header
        if symbolic_identity and ("=" in symbolic_identity or "==" in symbolic_identity):
            eq_parts = symbolic_identity.replace("==", "=").split("=")
            lhs = eq_parts[0].strip()
            rhs = eq_parts[1].strip()
            lines.append(f"theorem {clean_name} (x y : ℝ) : {lhs} = {rhs} := by")
        else:
            lines.append(f"theorem {clean_name} : True := by")

        # Tactic script
        if auto_tactics:
            for tac in auto_tactics:
                lines.append(f"  {tac}")
        else:
            lines.append("  trivial")

        lines.append("")
        lines.append("end CoResearcher.Discovery")
        return "\n".join(lines)

    @classmethod
    def audit_lean_source(
        cls,
        theorem_name: str,
        lean_code: str,
    ) -> LeanVerificationReport:
        """
        Audits Lean 4 source code:
        1. Checks for presence of unverified 'sorry' escapes.
        2. Detects axiomatic dependencies ('axiom').
        3. Identifies used proof tactics.
        4. Runs local Lean CLI compiler if installed on system.
        """
        if not lean_code.strip():
            return LeanVerificationReport(
                theorem_name=theorem_name,
                status=LeanProofStatus.UNVERIFIED_PROSE_ONLY,
                is_kernel_sound=False,
                contains_sorry=False,
                sorry_count=0,
                compiler_diagnostics="No Lean 4 code provided.",
                lean_source_code="",
                som_lean_formalization_hash="sha256:empty",
            )

        # 1. Static AST analysis for 'sorry' and 'axiom'
        sorry_matches = re.findall(r"\bsorry\b", lean_code)
        sorry_count = len(sorry_matches)
        has_sorry = sorry_count > 0

        axioms = re.findall(r"axiom\s+([a-zA-Z0-9_]+)", lean_code)

        # Extract tactics
        known_tactics = ["ring", "linarith", "norm_num", "simp", "intro", "intros", "cases", "induction", "apply", "exact", "trivial", "refl", "rw"]
        tactics_found = []
        for tac in known_tactics:
            if re.search(r"\b" + tac + r"\b", lean_code):
                tactics_found.append(tac)

        # 2. Local Compiler Execution Check
        lean_bin = shutil.which("lean")
        compiler_output = ""
        cli_success = False

        if lean_bin:
            try:
                with tempfile.NamedTemporaryFile(suffix=".lean", mode="w", delete=False, encoding="utf-8") as tmp:
                    tmp.write(lean_code)
                    tmp_path = tmp.name

                res = subprocess.run(
                    [lean_bin, tmp_path],
                    capture_output=True,
                    text=True,
                    timeout=30,
                )
                compiler_output = res.stdout + ("\n" + res.stderr if res.stderr else "")
                cli_success = (res.returncode == 0) and not has_sorry
                try:
                    os.remove(tmp_path)
                except Exception:
                    pass
            except Exception as e:
                compiler_output = f"Lean CLI invocation error: {str(e)}"
        else:
            compiler_output = (
                "Lean 4 binary not in system PATH. Only static checks ran ('sorry' and 'axiom' scan); "
                "the Lean kernel was not run, so the proof is not verified."
            )
            cli_success = False

        # 3. Determine Final Status
        if has_sorry:
            status = LeanProofStatus.CONTAINS_UNPROVEN_SORRY
            is_sound = False
        elif not lean_bin:
            status = LeanProofStatus.NOT_KERNEL_CHECKED
            is_sound = False
        elif cli_success:
            status = LeanProofStatus.FULLY_VERIFIED_KERNEL
            is_sound = True
        else:
            status = LeanProofStatus.SYNTAX_OR_TYPE_ERROR
            is_sound = False

        # SOM Hash
        sig_data = {
            "theorem": theorem_name,
            "status": status.value,
            "sorry": sorry_count,
            "tactics": tactics_found,
            "code_hash": hashlib.sha256(lean_code.encode("utf-8")).hexdigest()[:16],
        }
        som_hash = f"sha256:{hashlib.sha256(json.dumps(sig_data, sort_keys=True).encode('utf-8')).hexdigest()[:24]}"

        return LeanVerificationReport(
            theorem_name=theorem_name,
            status=status,
            is_kernel_sound=is_sound,
            contains_sorry=has_sorry,
            sorry_count=sorry_count,
            used_axioms=axioms,
            tactics_used=tactics_found,
            compiler_diagnostics=compiler_output.strip(),
            lean_source_code=lean_code,
            som_lean_formalization_hash=som_hash,
        )
