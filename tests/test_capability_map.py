"""The capability map, its registry file and the runtime catalogue agree.

docs/architecture/CAPABILITY_MAP.md and ecosystem/registry/capabilities.json are generated by
scripts/generate_capability_map.py. GET /api/capabilities (ADR-DISCOVERY-067) is built at runtime from the OpenAPI
contract. These tests keep the three from drifting apart.
"""

import importlib.util
import json
from pathlib import Path

from fastapi.testclient import TestClient

from api.server import app

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "ecosystem" / "registry" / "capabilities.json"


def _generator():
    spec = importlib.util.spec_from_file_location(
        "generate_capability_map", ROOT / "scripts" / "generate_capability_map.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _registry() -> dict:
    return json.loads(REGISTRY.read_text(encoding="utf-8"))


def test_map_and_registry_are_current():
    generator = _generator()
    model, problems = generator.build()
    assert problems == []
    assert REGISTRY.read_text(encoding="utf-8") == generator.render_registry(model)
    assert generator.MD_OUT.read_text(encoding="utf-8") == generator.render_markdown(model)


def test_catalogue_endpoints_are_exactly_the_registry_endpoints():
    catalogue = TestClient(app).get("/api/capabilities").json()["capabilities"]
    served = {f"{c['method']} {c['path']}" for c in catalogue}
    owners = {}
    for cap in _registry()["capabilities"]:
        for endpoint in cap["endpoints"]:
            assert endpoint not in owners, f"{endpoint} is in {owners.get(endpoint)} and {cap['id']}"
            owners[endpoint] = cap["id"]
    assert served == set(owners)


def test_catalogue_and_registry_report_the_same_maturity():
    maturity = {}
    for cap in _registry()["capabilities"]:
        maturity.update(cap["maturity"])
    catalogue = TestClient(app).get("/api/capabilities").json()["capabilities"]
    for item in catalogue:
        for module in item["modules"]:
            path = f"python/discovery/{module['module']}.py"
            assert maturity.get(path) == module["maturity"], (item["path"], path)
