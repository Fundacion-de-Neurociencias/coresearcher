"""Classifies every module of python/discovery by how the rest of the repository uses it.

This is a usage classification, not a judgment of scientific validity. Levels:

- Integrated: imported by the REST API (api/) and covered by a test in tests/.
- Tested: covered by a test in tests/ but not reachable from the API.
- Exercised: referenced only by a benchmark or demo script in scripts/.
- Prototype: no test, API route or script references the module.

Outputs docs/reference/MODULE_MATURITY.md and schemas/module_maturity.json.
Pass --check to fail when the committed outputs are stale (used in CI).
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DISCOVERY = ROOT / "python" / "discovery"
MD_OUT = ROOT / "docs" / "reference" / "MODULE_MATURITY.md"
JSON_OUT = ROOT / "schemas" / "module_maturity.json"
LEVELS = ["Integrated", "Tested", "Exercised", "Prototype"]


def _text_of(directory: Path) -> dict[str, str]:
    return {str(p.relative_to(ROOT)): p.read_text(encoding="utf-8", errors="ignore") for p in directory.rglob("*.py")}


def _mentions(corpus: dict[str, str], module: str) -> bool:
    pattern = re.compile(r"\b" + re.escape(module) + r"\b")
    return any(pattern.search(text) for text in corpus.values())


def classify() -> list[dict]:
    api = _text_of(ROOT / "api")
    tests = _text_of(ROOT / "tests")
    scripts = _text_of(ROOT / "scripts")
    rows = []
    for path in sorted(DISCOVERY.glob("*.py")):
        module = path.stem
        if module == "__init__":
            continue
        in_api = _mentions(api, module)
        in_tests = _mentions(tests, module)
        in_scripts = _mentions(scripts, module)
        if in_api and in_tests:
            level = "Integrated"
        elif in_tests:
            level = "Tested"
        elif in_scripts:
            level = "Exercised"
        else:
            level = "Prototype"
        rows.append({
            "module": module,
            "level": level,
            "api": in_api,
            "tests": in_tests,
            "scripts": in_scripts,
        })
    return rows


def render_markdown(rows: list[dict]) -> str:
    counts = {level: sum(r["level"] == level for r in rows) for level in LEVELS}
    lines = [
        "# Module maturity",
        "",
        "> Generated by [`scripts/generate_module_maturity.py`](../../scripts/generate_module_maturity.py). Do not edit by hand.",
        "",
        "This table records how each module of `python/discovery/` is used in the repository. It is not a",
        "judgment of scientific validity. A module can be well tested and still make claims that no benchmark",
        "supports; see the [claims register](CLAIMS_REGISTER.md) for that.",
        "",
        "| Level | Meaning | Modules |",
        "| --- | --- | --- |",
        f"| Integrated | Used by the API and covered by tests | {counts['Integrated']} |",
        f"| Tested | Covered by tests, not reachable from the API | {counts['Tested']} |",
        f"| Exercised | Referenced only by benchmark or demo scripts | {counts['Exercised']} |",
        f"| Prototype | No test, route or script references it | {counts['Prototype']} |",
        "",
        "| Module | Level | API | Tests | Scripts |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        mark = lambda flag: "yes" if flag else "-"
        lines.append(f"| `{r['module']}` | {r['level']} | {mark(r['api'])} | {mark(r['tests'])} | {mark(r['scripts'])} |")
    return "\n".join(lines) + "\n"


def render_json(rows: list[dict]) -> str:
    return json.dumps({"levels": LEVELS, "modules": rows}, indent=2, sort_keys=True) + "\n"


def main(argv: list[str]) -> int:
    rows = classify()
    outputs = {MD_OUT: render_markdown(rows), JSON_OUT: render_json(rows)}
    if "--check" in argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            for p in stale:
                print(f"{p.relative_to(ROOT)} is stale. Run: python scripts/generate_module_maturity.py")
            return 1
        print("Module maturity table is up to date.")
        return 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
