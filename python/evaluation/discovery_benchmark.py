"""
Discovery Benchmark - Sprint 22: Discovery Validation
Evaluates hypotheses for true scientific discovery potential.

Classification:
  A = Rephrasing (direct from claims)
  B = Synthesis (combination known)
  C = Inference (unstated connections)
  D = Discovery (no prior support)

This module addresses the core bottleneck identified in Sprint 20's Novelty Audit,
where 100% of hypotheses were Type B, indicating the system was only synthesizing
existing knowledge without generating true discovery.
"""

import json
from pathlib import Path
from typing import Dict, List, Optional
from dataclasses import dataclass, field
from datetime import datetime

# Security tier: PRIVATE — DO NOT MODIFY
# See python/_tiers.py for classification
SECURITY_TIER = "PRIVATE"


@dataclass
class DiscoveryMetrics:
    """Metrics for evaluating discovery quality."""
    novelty_score: float  # 0.0-1.0
    inference_score: float  # 0.0-1.0 - how much novel inference
    discovery_yield: int  # Count of Type C/D hypotheses
    novelty_class: str  # A|B|C|D
    mechanism_depth: int  # Levels of mechanism proposed
    cross_domain_connections: int  # Number of domains connected
    surprise_factor: float  # How unexpected is this?
    validation_path_clarity: float  # How testable is it?


@dataclass
class DiscoveryResult:
    """Result of evaluating a single hypothesis."""
    hypothesis_id: str
    question: str
    metrics: DiscoveryMetrics
    rationale: str
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())


@dataclass
class BenchmarkReport:
    """Complete benchmark report."""
    benchmark_name: str
    question: str
    hypotheses_evaluated: int
    results: List[DiscoveryResult]
    summary: Dict
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())


class DiscoveryBenchmark:
    """
    Evaluates the Discovery Engine output.
    
    Core Question: Can CoResearcher produce hypotheses that make us think
    "No había pensado en esto"?
    
    Flow:
      Question
      ↓
      Mechanism Discovery
      ↓
      Hypothesis Generation
      ↓
      Prediction
      ↓
      Refutation
      ↓
      Novel Discovery
    """
    
    DISCOVERY_PATTERNS = {
        # Type A: Direct rephrasing - just restating claims
        "direct_rephrase": [
            "predicts", "associated with", "diagnoses", "treats",
            "causes", "increases", "decreases"
        ],
        
        # Type B: Literature synthesis - known combinations
        "synthesis_patterns": [
            "combined with", "together with", "in combination",
            "alongside", "co-occurs"
        ],
        
        # Type C: Novel inference - unstated connections
        "novel_inference": [
            "mediator", "mechanism", "synergistic", "threshold effect",
            "compensatory", "feedback loop", "emergent property",
            "hidden variable", "moderator", "confounder"
        ],
        
        # Type D: Potential discovery - fundamental reframing
        "discovery_patterns": [
            "what if", "instead of", "rather than", "inverse",
            "reverse causality", "protective response", "adaptation",
            "paradigm shift", "fundamentally", "novel pathway"
        ],
        
        # Cross-domain indicators (boosts C/D)
        "cross_domain": [
            "between", "links", "connects", "mediates",
            "bridges", "transfers", "translates"
        ],
        
        # Mechanism depth indicators
        "mechanism_depth": [
            "mechanism", "pathway", "cascade", "signaling",
            "regulatory", "feedback", "network", "loop", "process"
        ]
    }
    
    def __init__(self):
        self.benchmark_dir = Path("evaluation/benchmarks")
        self.results_dir = Path("evaluation/results")
        self.benchmark_dir.mkdir(parents=True, exist_ok=True)
        self.results_dir.mkdir(parents=True, exist_ok=True)
    
    def evaluate_discovery(
        self,
        question: str,
        generated_hypotheses: List[Dict]
    ) -> BenchmarkReport:
        """
        Evaluate discovered hypotheses for true discovery potential.
        
        Args:
            question: The original research question
            generated_hypotheses: List of hypotheses generated by the system
            
        Returns:
            BenchmarkReport with metrics for each hypothesis
        """
        results = []
        
        for hyp in generated_hypotheses:
            statement = hyp.get("statement", "")
            hyp_id = hyp.get("id", "unknown")
            
            # Calculate metrics
            metrics = self._calculate_metrics(statement, hyp)
            novelty_class = self._classify_novelty(metrics, statement)
            
            # Build rationale
            rationale = self._build_rationale(statement, metrics, novelty_class)
            
            result = DiscoveryResult(
                hypothesis_id=hyp_id,
                question=question,
                metrics=metrics,
                rationale=rationale
            )
            results.append(result)
        
        # Summary statistics
        summary = {
            "total_hypotheses": len(results),
            "type_a_count": len([r for r in results if r.metrics.novelty_class == "A"]),
            "type_b_count": len([r for r in results if r.metrics.novelty_class == "B"]),
            "type_c_count": len([r for r in results if r.metrics.novelty_class == "C"]),
            "type_d_count": len([r for r in results if r.metrics.novelty_class == "D"]),
            "avg_novelty_score": sum(r.metrics.novelty_score for r in results) / len(results) if results else 0,
            "avg_inference_score": sum(r.metrics.inference_score for r in results) / len(results) if results else 0,
            "max_mechanism_depth": max((r.metrics.mechanism_depth for r in results), default=0),
            "total_cross_domain": sum(r.metrics.cross_domain_connections for r in results),
            "discovery_hypotheses": [r.hypothesis_id for r in results if r.metrics.novelty_class in ["C", "D"]],
            "breakthrough_potential": any(r.metrics.novelty_class == "D" for r in results),
        }
        
        return BenchmarkReport(
            benchmark_name="discovery_benchmark",
            question=question,
            hypotheses_evaluated=len(results),
            results=results,
            summary=summary
        )
    
    def _calculate_metrics(self, statement: str, hyp: Dict) -> DiscoveryMetrics:
        """Calculate detailed metrics for a hypothesis."""
        stmt_lower = statement.lower()
        
        # Check for direct claim rephrasing (Type A)
        direct_matches = sum(1 for p in self.DISCOVERY_PATTERNS["direct_rephrase"] if p in stmt_lower)
        
        # Check for synthesis patterns (Type B)
        synthesis_matches = sum(1 for p in self.DISCOVERY_PATTERNS["synthesis_patterns"] if p in stmt_lower)
        
        # Check for novel inference patterns (Type C/D)
        inference_matches = sum(1 for p in self.DISCOVERY_PATTERNS["novel_inference"] if p in stmt_lower)
        discovery_matches = sum(1 for p in self.DISCOVERY_PATTERNS["discovery_patterns"] if p in stmt_lower)
        cross_domain_matches = sum(1 for p in self.DISCOVERY_PATTERNS["cross_domain"] if p in stmt_lower)
        
        # Mechanism depth
        mechanism_depth = sum(1 for p in self.DISCOVERY_PATTERNS["mechanism_depth"] if p in stmt_lower)
        
        # Surprise factor: based on unexpected framing
        surprise_indicators = [
            "inverse", "reverse", "protective", "adaptive", "paradigm",
            "contrary", "unexpected", "counterintuitive", "novel"
        ]
        surprise_score = sum(1 for p in surprise_indicators if p in stmt_lower) / len(surprise_indicators)
        
        # Validation path clarity
        validation_indicators = ["test", "validate", "experiment", "measure", "observe", "trial"]
        validation_score = min(1.0, sum(1 for p in validation_indicators if p in stmt_lower) / 3.0)
        
        # Calculate scores
        if direct_matches > 0 and synthesis_matches == 0:
            # Type A: Direct rephrasing
            novelty_score = 0.1
            inference_score = 0.0
        elif direct_matches == 0 and synthesis_matches > 0:
            # Type B: Synthesis
            novelty_score = 0.3
            inference_score = 0.1
        elif inference_matches > 0 or discovery_matches > 0:
            # Type C or D: Novel inference/discovery
            base_score = 0.7 if inference_matches > 0 else 0.9
            novelty_score = min(1.0, base_score + (cross_domain_matches * 0.1))
            inference_score = min(1.0, 0.5 + (mechanism_depth * 0.15))
        else:
            # Default to synthesis
            novelty_score = 0.4
            inference_score = 0.2
        
        return DiscoveryMetrics(
            novelty_score=novelty_score,
            inference_score=inference_score,
            discovery_yield=1 if novelty_score >= 0.7 else 0,
            novelty_class="",  # Will be set by classifier
            mechanism_depth=mechanism_depth,
            cross_domain_connections=cross_domain_matches,
            surprise_factor=surprise_score,
            validation_path_clarity=validation_score
        )
    
    def _classify_novelty(self, metrics: DiscoveryMetrics, statement: str) -> str:
        """Classify hypothesis novelty type based on patterns and scores."""
        stmt_lower = statement.lower() if statement else ""
        
        # Type D: Discovery patterns (most novel) - fundamental reframing
        discovery_keywords = ["what if", "instead of", "rather than", "inverse", 
                              "reverse causality", "protective", "adaptation", "reframes"]
        has_discovery_reframing = any(kw in stmt_lower for kw in discovery_keywords)
        
        # Type C: Novel inference - mediator/hidden/threshold patterns
        inference_keywords = ["mediator", "mechanism", "synergistic", "threshold",
                             "compensatory", "feedback loop", "emergent", "hidden",
                             "moderator", "confounder", "hidden mediator", "threshold-dependent"]
        has_inference = any(kw in stmt_lower for kw in inference_keywords)
        
        # Type A: Direct rephrasing - direct claim language
        rephrase_keywords = ["predicts", "associated with", "diagnoses", "treats",
                            "causes", "increases", "decreases"]
        has_rephrase = any(kw in stmt_lower for kw in rephrase_keywords)
        
        # Classification logic - order matters: D > C > A > B
        if has_discovery_reframing or "what if" in stmt_lower:
            return "D"
        elif has_inference:
            return "C"
        elif has_rephrase:
            return "A"
        else:
            # Check if novelty score indicates C/D even without keywords
            if metrics.novelty_score >= 0.7:
                return "C"
            return "B"  # Default to synthesis
    
    def _build_rationale(self, statement: str, metrics: DiscoveryMetrics, novelty_class: str) -> str:
        """Build human-readable rationale for the evaluation."""
        rationales = {
            "A": "Direct rephrasing of existing literature claims",
            "B": f"Literature synthesis combining known elements (cross-domain: {metrics.cross_domain_connections})",
            "C": f"Novel inference with {metrics.mechanism_depth} mechanism levels (surprise: {metrics.surprise_factor:.2f})",
            "D": f"Potential discovery - fundamental reframing detected (validation path: {metrics.validation_path_clarity:.2f})"
        }
        return rationales.get(novelty_class, "Unknown classification")
    
