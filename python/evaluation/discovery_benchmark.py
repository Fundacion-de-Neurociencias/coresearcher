    def _get_benchmark_questions(self, domain: str) -> List[Dict]:
        """Get standard benchmark questions for domain."""
        benchmark_files = list(self.benchmark_dir.glob(f"*.json"))
        
        all_questions = []
        for bf in benchmark_files:
            with open(bf, 'r') as f:
                data = json.load(f)
                all_questions.extend(data.get("questions", []))
        
