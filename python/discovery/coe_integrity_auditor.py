"""
python/discovery/coe_integrity_auditor.py - CoE Integrity Audit & Active Empirical Rebuttal Engine (ADR-DISCOVERY-077)
Inspired by ScientistTwo (Google Cloud AI Research, 2026).

Enforces:
1. Four-Dimensional Integrity Audit:
   - Score Verification: Re-running code reproduces reported numbers within strict tolerance.
   - Specification Compliance: Verifies zero rule-breaking, bounded parameters, and physical laws (anti-reward hacking).
   - Reference Verification: Grounds and audits all bibliographic citations (zero hallucinated citations).
   - Method-Code Alignment: Verifies that claimed theoretical constructs exist as executable symbols in the codebase.
2. Active Empirical Rebuttal: Rather than defending manuscripts with rhetorical text adjustments,
   dispatches targeted empirical experiments (CFD oracles, contact dynamics, Cartan-DEC audits)
   to resolve reviewer objections with reproducible telemetry and ground truth.
"""

from __future__ import annotations
from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import Dict, Any, List, Optional, Tuple, Callable
import hashlib
import json
import math
import time


class IntegrityDimension(str, Enum):
    SCORE_VERIFICATION = "SCORE_VERIFICATION"
    SPECIFICATION_COMPLIANCE = "SPECIFICATION_COMPLIANCE"
    REFERENCE_VERIFICATION = "REFERENCE_VERIFICATION"
    METHOD_CODE_ALIGNMENT = "METHOD_CODE_ALIGNMENT"


class EmpiricalRebuttalVerdict(str, Enum):
    EMPIRICALLY_VERIFIED = "EMPIRICALLY_VERIFIED"
    EMPIRICALLY_FALSIFIED = "EMPIRICALLY_FALSIFIED"
    INCONCLUSIVE_DATA = "INCONCLUSIVE_DATA"


@dataclass
class IntegrityAuditResult:
    """Outcome of auditing a single integrity dimension."""
    dimension: IntegrityDimension
    passed: bool
    score: float                    # In [0.0, 1.0], 1.0 = flawless
    details: Dict[str, Any]
    violations_count: int
    execution_hash: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "dimension": self.dimension.value,
            "passed": self.passed,
            "score": self.score,
            "details": self.details,
            "violations_count": self.violations_count,
            "execution_hash": self.execution_hash
        }


@dataclass
class EmpiricalRebuttalDossier:
    """
    Evidence dossier generated by actively executing a targeted experiment
    in response to an adversarial review objection.
    """
    objection_id: str
    reviewer_critique: str
    experiment_name: str
    execution_time_seconds: float
    telemetry_output: Dict[str, Any]
    rebuttal_verdict: EmpiricalRebuttalVerdict
    justification: str
    reproducibility_hash: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "objection_id": self.objection_id,
            "reviewer_critique": self.reviewer_critique,
            "experiment_name": self.experiment_name,
            "execution_time_seconds": self.execution_time_seconds,
            "telemetry_output": self.telemetry_output,
            "rebuttal_verdict": self.rebuttal_verdict.value,
            "justification": self.justification,
            "reproducibility_hash": self.reproducibility_hash
        }


@dataclass
class FullCoEIntegrityReport:
    """Master report compiling the 4-way integrity audit and empirical rebuttals."""
    target_id: str
    audit_timestamp: float
    dimension_results: List[IntegrityAuditResult]
    rebuttal_dossiers: List[EmpiricalRebuttalDossier]
    overall_integrity_score: float  # In [0.0, 1.0]
    all_dimensions_passed: bool
    verdict: str
    master_hash: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "target_id": self.target_id,
            "audit_timestamp": self.audit_timestamp,
            "dimension_results": [r.to_dict() for r in self.dimension_results],
            "rebuttal_dossiers": [d.to_dict() for d in self.rebuttal_dossiers],
            "overall_integrity_score": self.overall_integrity_score,
            "all_dimensions_passed": self.all_dimensions_passed,
            "verdict": self.verdict,
            "master_hash": self.master_hash
        }


class CoEIntegrityAuditor:
    """
    CoE Integrity Auditor enforcing rigorous post-hoc verification
    and empirical rebuttal dispatching.
    """

    def __init__(self, numeric_tolerance: float = 1e-4):
        self.numeric_tolerance = numeric_tolerance

    def verify_scores(
        self,
        claimed_scores: Dict[str, float],
        reproduced_scores: Dict[str, float],
        tolerance: Optional[float] = None
    ) -> IntegrityAuditResult:
        """
        Verify that all numbers reported in a paper or claim are exactly reproducible
        by running the pipeline, without drift or manual fabrication.
        """
        tol = tolerance if tolerance is not None else self.numeric_tolerance
        discrepancies: Dict[str, Dict[str, float]] = {}
        total_keys = len(claimed_scores)

        for key, claimed_val in claimed_scores.items():
            if key not in reproduced_scores:
                discrepancies[key] = {"claimed": claimed_val, "reproduced": None, "diff": float("inf")}
                continue
            reproduced_val = reproduced_scores[key]
            diff = abs(claimed_val - reproduced_val)
            if diff > tol:
                discrepancies[key] = {"claimed": claimed_val, "reproduced": reproduced_val, "diff": diff}

        violations = len(discrepancies)
        score = 1.0 if total_keys == 0 else max(0.0, (total_keys - violations) / total_keys)
        passed = (violations == 0)

        payload = {"claimed": claimed_scores, "reproduced": reproduced_scores, "violations": violations}
        h = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()

        return IntegrityAuditResult(
            dimension=IntegrityDimension.SCORE_VERIFICATION,
            passed=passed,
            score=score,
            details={"discrepancies": discrepancies, "tolerance": tol},
            violations_count=violations,
            execution_hash=h
        )

    def verify_specification_compliance(
        self,
        constraints: Dict[str, Tuple[float, float]],
        observed_metrics: Dict[str, float]
    ) -> IntegrityAuditResult:
        """
        Verify that physical and benchmark boundary constraints are strictly honored
        (e.g., energy E >= 0, divergence <= tol, probability in [0, 1]).
        """
        violations: Dict[str, Dict[str, Any]] = {}
        total = len(constraints)

        for metric_name, (min_val, max_val) in constraints.items():
            if metric_name not in observed_metrics:
                violations[metric_name] = {"reason": "MISSING_OBSERVED_METRIC"}
                continue
            val = observed_metrics[metric_name]
            if val < min_val or val > max_val:
                violations[metric_name] = {
                    "reason": "OUT_OF_BOUNDS",
                    "observed": val,
                    "expected_range": [min_val, max_val]
                }

        v_count = len(violations)
        score = 1.0 if total == 0 else max(0.0, (total - v_count) / total)
        passed = (v_count == 0)

        payload = {"constraints": constraints, "observed": observed_metrics, "violations": v_count}
        h = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()

        return IntegrityAuditResult(
            dimension=IntegrityDimension.SPECIFICATION_COMPLIANCE,
            passed=passed,
            score=score,
            details={"violations": violations},
            violations_count=v_count,
            execution_hash=h
        )

    def verify_references(
        self,
        citations: List[Dict[str, str]]
    ) -> IntegrityAuditResult:
        """
        Verify that all bibliographical citations have verified DOIs, PMIDs, or verified titles,
        rejecting placeholder citations (e.g. PMID_1234, generic placeholders).
        """
        invalid_citations: List[Dict[str, str]] = []
        total = len(citations)

        for cit in citations:
            title = cit.get("title", "").strip()
            identifier = cit.get("doi", "") or cit.get("pmid", "")
            year = cit.get("year", "")

            # Reject known placeholder patterns per ADR-013 / theater scan rules
            if not title or not identifier or "generic" in identifier.lower() or "1234" in identifier:
                invalid_citations.append(cit)
            elif not year or not year.isdigit() or int(year) < 1800 or int(year) > 2030:
                invalid_citations.append(cit)

        v_count = len(invalid_citations)
        score = 1.0 if total == 0 else max(0.0, (total - v_count) / total)
        passed = (v_count == 0)

        payload = {"total": total, "invalid_count": v_count}
        h = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()

        return IntegrityAuditResult(
            dimension=IntegrityDimension.REFERENCE_VERIFICATION,
            passed=passed,
            score=score,
            details={"invalid_citations": invalid_citations},
            violations_count=v_count,
            execution_hash=h
        )

    def verify_method_code_alignment(
        self,
        claimed_method_terms: List[str],
        available_code_symbols: Set[str]
    ) -> IntegrityAuditResult:
        """
        Verify that mathematical concepts claimed in manuscript text actually correspond
        to executable methods and classes in the codebase.
        """
        missing_terms: List[str] = []
        total = len(claimed_method_terms)

        for term in claimed_method_terms:
            # Check direct or normalized match
            term_clean = term.lower().replace("-", "").replace("_", "")
            match_found = any(term_clean in sym.lower().replace("-", "").replace("_", "") for sym in available_code_symbols)
            if not match_found:
                missing_terms.append(term)

        v_count = len(missing_terms)
        score = 1.0 if total == 0 else max(0.0, (total - v_count) / total)
        passed = (v_count == 0)

        payload = {"claimed_terms": claimed_method_terms, "missing_count": v_count}
        h = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()

        return IntegrityAuditResult(
            dimension=IntegrityDimension.METHOD_CODE_ALIGNMENT,
            passed=passed,
            score=score,
            details={"missing_terms": missing_terms},
            violations_count=v_count,
            execution_hash=h
        )

    def execute_active_empirical_rebuttal(
        self,
        objection_id: str,
        reviewer_critique: str,
        experiment_name: str,
        experiment_fn: Callable[..., Any],
        assertion_fn: Callable[[Any], Tuple[bool, str]],
        *args,
        **kwargs
    ) -> EmpiricalRebuttalDossier:
        """
        Actively execute a targeted empirical experiment to answer a reviewer objection,
        capturing execution time, full telemetry, and an assertion verdict.
        """
        t0 = time.perf_counter()
        telemetry: Dict[str, Any] = {}
        verdict = EmpiricalRebuttalVerdict.INCONCLUSIVE_DATA
        justification = ""

        try:
            exp_result = experiment_fn(*args, **kwargs)
            t_elapsed = time.perf_counter() - t0

            if hasattr(exp_result, "to_dict"):
                telemetry = exp_result.to_dict()
            elif isinstance(exp_result, dict):
                telemetry = exp_result
            else:
                telemetry = {"raw_result": str(exp_result)}

            passed, assertion_msg = assertion_fn(exp_result)
            if passed:
                verdict = EmpiricalRebuttalVerdict.EMPIRICALLY_VERIFIED
                justification = f"Experiment '{experiment_name}' confirmed claim: {assertion_msg}"
            else:
                verdict = EmpiricalRebuttalVerdict.EMPIRICALLY_FALSIFIED
                justification = f"Experiment '{experiment_name}' falsified claim: {assertion_msg}"

        except Exception as e:
            t_elapsed = time.perf_counter() - t0
            telemetry = {"error": str(e)}
            verdict = EmpiricalRebuttalVerdict.INCONCLUSIVE_DATA
            justification = f"Experiment execution failed with exception: {e}"

        payload = {
            "objection_id": objection_id,
            "experiment_name": experiment_name,
            "verdict": verdict.value,
            "elapsed": round(t_elapsed, 4)
        }
        repro_hash = hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()

        return EmpiricalRebuttalDossier(
            objection_id=objection_id,
            reviewer_critique=reviewer_critique,
            experiment_name=experiment_name,
            execution_time_seconds=t_elapsed,
            telemetry_output=telemetry,
            rebuttal_verdict=verdict,
            justification=justification,
            reproducibility_hash=repro_hash
        )

    def audit_full_integrity(
        self,
        target_id: str,
        claimed_scores: Dict[str, float],
        reproduced_scores: Dict[str, float],
        constraints: Dict[str, Tuple[float, float]],
        observed_metrics: Dict[str, float],
        citations: List[Dict[str, str]],
        claimed_method_terms: List[str],
        available_code_symbols: Set[str],
        rebuttal_dossiers: Optional[List[EmpiricalRebuttalDossier]] = None
    ) -> FullCoEIntegrityReport:
        """
        Run the complete 4-dimensional CoE Integrity Audit and aggregate scores.
        """
        r_scores = self.verify_scores(claimed_scores, reproduced_scores)
        r_spec = self.verify_specification_compliance(constraints, observed_metrics)
        r_refs = self.verify_references(citations)
        r_align = self.verify_method_code_alignment(claimed_method_terms, available_code_symbols)

        results = [r_scores, r_spec, r_refs, r_align]
        mean_score = sum(r.score for r in results) / len(results)
        all_passed = all(r.passed for r in results)

        dossiers = rebuttal_dossiers or []
        verdict = "PASSED_PUBLICATION_BAR" if (all_passed and mean_score >= 0.95) else "REJECTED_INTEGRITY_VIOLATION"

        master_payload = {
            "target_id": target_id,
            "mean_score": round(mean_score, 4),
            "all_passed": all_passed,
            "rebuttal_count": len(dossiers)
        }
        master_hash = hashlib.sha256(json.dumps(master_payload, sort_keys=True).encode()).hexdigest()

        return FullCoEIntegrityReport(
            target_id=target_id,
            audit_timestamp=time.time(),
            dimension_results=results,
            rebuttal_dossiers=dossiers,
            overall_integrity_score=mean_score,
            all_dimensions_passed=all_passed,
            verdict=verdict,
            master_hash=master_hash
        )
