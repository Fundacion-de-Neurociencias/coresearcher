"""Computes 95% Wilson score intervals for the benchmark proportions.

Input: docs/reference/benchmark_counts.json (counts printed by each benchmark).
Output: docs/reference/CONFIDENCE_INTERVALS.md (generated; do not edit by hand).

The Wilson interval is preferred to the normal approximation because it behaves
well for small samples and for proportions near 0 or 1, which several benchmarks
produce. Pass --check to fail when the committed report is stale (used in CI).
"""

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COUNTS = ROOT / "docs" / "reference" / "benchmark_counts.json"
OUTPUT = ROOT / "docs" / "reference" / "CONFIDENCE_INTERVALS.md"
Z_95 = 1.959963984540054
SMALL_SAMPLE = 30


def wilson(successes: int, trials: int, z: float = Z_95) -> tuple[float, float]:
    if trials <= 0 or not 0 <= successes <= trials:
        raise ValueError(f"invalid counts: {successes}/{trials}")
    p = successes / trials
    denom = 1 + z * z / trials
    centre = (p + z * z / (2 * trials)) / denom
    half = z * math.sqrt(p * (1 - p) / trials + z * z / (4 * trials * trials)) / denom
    return max(0.0, centre - half), min(1.0, centre + half)


def render() -> str:
    data = json.loads(COUNTS.read_text(encoding="utf-8"))
    lines = [
        "# Confidence intervals for benchmark results",
        "",
        "> Generated by [`scripts/compute_confidence_intervals.py`](../../scripts/compute_confidence_intervals.py) "
        "from [`benchmark_counts.json`](benchmark_counts.json). Do not edit by hand.",
        "",
        f"Snapshot: {data['snapshot']}. Environment: {data['environment']}.",
        "",
        "These intervals quantify sampling uncertainty of the **internal** benchmark outcomes only. They do not",
        "measure agreement with external data, which has not been tested (see the limitations section).",
        "Intervals are 95% Wilson score intervals. Rows marked *small sample* have fewer than "
        f"{SMALL_SAMPLE} trials, so the interval is very wide and should not be read as a precise estimate.",
        "",
        "| Benchmark | Metric | Result | 95% CI | Note |",
        "| --- | --- | --- | --- | --- |",
    ]
    for m in data["measurements"]:
        k, n = m["successes"], m["trials"]
        lo, hi = wilson(k, n)
        note = "small sample" if n < SMALL_SAMPLE else ""
        lines.append(
            f"| {m['benchmark']} | {m['metric']} | {k}/{n} = {100 * k / n:.1f}% | [{100 * lo:.1f}%, {100 * hi:.1f}%] | {note} |"
        )
    lines += [
        "",
        "## Limitations",
        "",
        "- Intervals assume the trials are independent and drawn from the same distribution. Benchmark cases are",
        "  hand-built or synthetic (see the [claims register](CLAIMS_REGISTER.md)), so the intervals describe",
        "  behaviour on those cases, not on real research corpora.",
        "- Outcomes whose denominator is not printed by the script are excluded, for example the self-correction",
        "  rate of the adversarial suite.",
        "- No external validation has been performed yet. Adding one requires public datasets and a pre-registered",
        "  protocol; it is tracked as an open item in the claims register.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    content = render()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT.relative_to(ROOT)} is stale. Run: python scripts/compute_confidence_intervals.py")
            return 1
        print("Confidence intervals are up to date.")
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
